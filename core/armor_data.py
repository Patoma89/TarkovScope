GEAR_CATEGORIES = [
    "Todos",
    "Placas Balísticas",
    "Chalecos Blindados",
    "Rigs Blindados",
    "Cascos Blindados",
    "Auriculares",
]


def get_all_protection_items() -> List[Dict[str, Any]]:
    """Retorna el catálogo unificado de placas, chalecos, rigs blindados, cascos y auriculares."""
    return (
        ARMOR_PLATES_CATALOG
        + ARMOR_VESTS_CATALOG
        + ARMORED_RIGS_CATALOG
        + HELMETS_CATALOG
        + HEADSETS_CATALOG
    )


def filter_protection_items(
    category: str = "Todos",
    min_class: int = 0,
    query: str = "",
    headset_only_compat: bool = False,
) -> List[Dict[str, Any]]:
    """Filtra blindajes, placas, cascos y auriculares por tipo, clase mínima, compatibilidad y texto."""
    q = (query or "").strip().lower()
    cat_map = {
        "Placas Balísticas": ARMOR_PLATES_CATALOG,
        "Chalecos Blindados": ARMOR_VESTS_CATALOG,
        "Rigs Blindados": ARMORED_RIGS_CATALOG,
        "Cascos Blindados": HELMETS_CATALOG,
        "Auriculares": HEADSETS_CATALOG,
    }
    source = cat_map.get(category) if category in cat_map else get_all_protection_items()
    results: List[Dict[str, Any]] = []
    for item in source:
        ac = int(item.get("armor_class", 0) or 0)
        if min_class > 0 and ac < min_class:
            continue
        if headset_only_compat:
            if item.get("category") == "Casco Blindado" and item.get("headset_compat") == "Bloquea Auriculares":
                continue
        if q:
            hay = " ".join([
                str(item.get("name", "")),
                str(item.get("category", "")),
                str(item.get("material", "")),
                str(item.get("areas", "")),
                str(item.get("default_plates", "")),
                str(item.get("headset_compat", "")),
                str(item.get("audio_profile", "")),
            ]).lower()
            if q not in hay:
                continue
        results.append(item)
    return results
