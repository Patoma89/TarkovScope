CONTAINER_CATEGORIES = [
    "Todos",
    "Contenedor Seguro",
    "Caja / Contenedor",
    "Mochila",
    "Rig Táctico",
]


def get_all_storage_items() -> List[Dict[str, Any]]:
    """Retorna todos los contenedores, mochilas y rigs tácticos."""
    return (
        SECURE_CONTAINERS_CATALOG
        + STASH_CONTAINERS_CATALOG
        + BACKPACKS_CATALOG
        + UNARMORED_RIGS_CATALOG
    )


def filter_storage_items(
    category: str = "Todos",
    query: str = "",
    only_in_secure: bool = False,
    only_2x2_rigs: bool = False,
    only_1x3_rigs: bool = False,
) -> List[Dict[str, Any]]:
    """Filtra contenedores, mochilas y rigs por categoría, compatibilidad en pouch o slots 2x2/1x3."""
    q = (query or "").strip().lower()
    cat_map = {
        "Contenedor Seguro": SECURE_CONTAINERS_CATALOG,
        "Caja / Contenedor": STASH_CONTAINERS_CATALOG,
        "Mochila": BACKPACKS_CATALOG,
        "Rig Táctico": UNARMORED_RIGS_CATALOG,
    }
    source = cat_map.get(category) if category in cat_map else get_all_storage_items()
    results: List[Dict[str, Any]] = []
    for item in source:
        if only_in_secure and item.get("in_secure") != "Sí":
            continue
        if only_2x2_rigs and not item.get("has_2x2"):
            continue
        if only_1x3_rigs and not item.get("has_1x3"):
            continue
        if q:
            hay = " ".join([
                str(item.get("name", "")),
                str(item.get("category", "")),
                str(item.get("holds", "")),
                str(item.get("layout", "")),
                str(item.get("trader", "")),
            ]).lower()
            if q not in hay:
                continue
        results.append(item)
    return results
