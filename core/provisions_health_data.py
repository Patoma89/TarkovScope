def filter_provisions(
    category: str = "Todas",
    query: str = "",
    only_buffs: bool = False,
    only_fir: bool = False,
) -> List[Dict[str, Any]]:
    """Filtra el catálogo de provisiones por categoría, búsqueda, buffs o relevancia FiR."""
    q = (query or "").strip().lower()
    res: List[Dict[str, Any]] = []
    for p in PROVISIONS_CATALOG:
        if category and category != "Todas" and p.get("category") != category:
            continue
        if only_buffs and p.get("meta_tier") not in ("S", "A") and "+" not in p.get("buffs_es", ""):
            continue
        if only_fir and not p.get("is_barter") and not p.get("is_craft") and "quest" not in p.get("fir_usage_es", "").lower() and "hideout" not in p.get("fir_usage_es", "").lower():
            continue
        if q:
            haystack = " ".join([
                p.get("name", ""),
                p.get("short_name", ""),
                p.get("category", ""),
                p.get("buffs_es", ""),
                p.get("buffs_en", ""),
                p.get("fir_usage_es", ""),
                p.get("fir_usage_en", ""),
            ]).lower()
            if q not in haystack:
                continue
        res.append(p)
    return res
