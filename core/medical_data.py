def filter_medical_items(
    category: str = "Todas",
    symptom: str = "all",
    query: str = "",
) -> List[Dict[str, Any]]:
    """Filtra el catálogo médico por categoría, síntoma que trata y texto de búsqueda."""
    q = (query or "").strip().lower()
    results: List[Dict[str, Any]] = []
    for item in MEDICAL_CATALOG:
        if category and category != "Todas" and item["category"] != category:
            continue
        if symptom and symptom != "all" and symptom not in item.get("cures", []):
            continue
        if q:
            haystack = " ".join([
                item.get("name", ""),
                item.get("category", ""),
                item.get("cures_label", ""),
                item.get("positive_effects", ""),
                item.get("tactical_tip", ""),
            ]).lower()
            if q not in haystack:
                continue
        results.append(item)
    return results
